public class Loops {
  public static void main(String[] args) {
    // While loops
    // while (condition) {
    //   code
    // }
    // example:
    int i = 5;
    while (i > 1) {
      System.out.println(i);
      i--;
    }

    // do-while looooop
    // do {
    // code to be executed 
    // } while (condition);
    
    int j = 6;
    do {
      System.out.println(j);
      i++;
    } while (i < 6); // this code will run one time

    // for loops
    for (int y = 5; y > 0; y--) {
      System.out.println(y);
    }
    


  }
}
